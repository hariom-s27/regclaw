def render_cmd(numbers_path_str: str, template_path_str: str, block_template_path_str: str,
               results_out_str: str, results_md_str: str) -> int:
    numbers_path = Path(numbers_path_str)
    template_path = Path(template_path_str)
    block_template_path = Path(block_template_path_str)
    results_out = Path(results_out_str)
    results_md = Path(results_md_str)

    numbers_data = json.loads(numbers_path.read_text(encoding="utf-8"))
    variables = build_formatted_vars(numbers_data)

    template_text = template_path.read_text(encoding="utf-8")
    block_template_text = block_template_path.read_text(encoding="utf-8")

    rendered_doc = substitute(template_text, variables)
    rendered_block = substitute(block_template_text, variables)

    # Write results_s10c_dev.md with LF endings
    results_out.parent.mkdir(parents=True, exist_ok=True)
    with results_out.open("w", encoding="utf-8", newline="\n") as f:
        f.write(rendered_doc.replace("\r\n", "\n"))

    # Update docs/results.md
    if results_md.exists():
        md_text = results_md.read_text(encoding="utf-8").replace("\r\n", "\n")
    else:
        md_text = ""

    start_marker = "<!-- S10c:start -->"
    end_marker = "<!-- S10c:end -->"

    if start_marker in md_text and end_marker in md_text:
        before = md_text.split(start_marker)[0]
        after = md_text.split(end_marker)[1]
        new_md = f"{before}{start_marker}\n{rendered_block.strip()}\n{end_marker}{after}"
    else:
        separator = "\n\n" if md_text and not md_text.endswith("\n\n") else ("\n" if md_text and not md_text.endswith("\n") else "")
        new_md = f"{md_text}{separator}{start_marker}\n{rendered_block.strip()}\n{end_marker}\n"

    results_md.parent.mkdir(parents=True, exist_ok=True)
    with results_md.open("w", encoding="utf-8", newline="\n") as f:
        f.write(new_md.replace("\r\n", "\n"))

    print(f"render complete: {results_out} and {results_md}")
    return 0


def check_cmd(rendered_path_str: str, results_md_str: str, numbers_path_str: str, allowlist_path_str: str) -> int:
    rendered_path = Path(rendered_path_str)
    results_md = Path(results_md_str)
    numbers_path = Path(numbers_path_str)
    allowlist_path = Path(allowlist_path_str)

    if not rendered_path.exists():
        sys.stderr.write(f"file_not_found: {rendered_path}\n")
        return 1
    if not results_md.exists():
        sys.stderr.write(f"file_not_found: {results_md}\n")
        return 1

    numbers_data = json.loads(numbers_path.read_text(encoding="utf-8"))
    variables = build_formatted_vars(numbers_data)

    # Collect all rendered values from variables and numbers_data
    allowed_values: Set[str] = set()

    def collect_values(val: Any):
        if val is None:
            return
        if isinstance(val, (int, float, str)):
            s = str(val).strip()
            if s:
                allowed_values.add(s)
        elif isinstance(val, dict):
            for k, v in val.items():
                collect_values(k)
                collect_values(v)
        elif isinstance(val, (list, tuple)):
            for item in val:
                collect_values(item)

    collect_values(variables)
    collect_values(numbers_data)

    # Add numeric tokens from formatted values (e.g. "0.000 (0/40)" -> "0.000", "0", "40", "0/40")
    expanded_allowed: Set[str] = set(allowed_values)
    for s in list(allowed_values):
        for num_match in re.finditer(r"\b\d+(?:\.\d+)?(?:/\d+)?\b", s):
            expanded_allowed.add(num_match.group(0))
        for d in re.finditer(r"\d+", s):
            expanded_allowed.add(d.group(0))

    # Load context pattern allowlist
    allowlist_items = json.loads(allowlist_path.read_text(encoding="utf-8"))
    allowlist_patterns: List[re.Pattern] = []
    for item in allowlist_items:
        p = item.get("pattern")
        if p:
            allowlist_patterns.append(re.compile(p, re.IGNORECASE | re.MULTILINE))

    # Texts to check
    full_rendered = rendered_path.read_text(encoding="utf-8")
    md_content = results_md.read_text(encoding="utf-8")
    start_marker = "<!-- S10c:start -->"
    end_marker = "<!-- S10c:end -->"
    if start_marker in md_content and end_marker in md_content:
        block_text = md_content.split(start_marker)[1].split(end_marker)[0]
    else:
        sys.stderr.write("missing_s10c_markers_in_results_md\n")
        return 1

    targets = [
        ("results_s10c_dev.md", full_rendered),
        ("results.md (S10c block)", block_text)
    ]

    stray_numbers: List[Dict[str, Any]] = []

    for doc_name, text in targets:
        # Check that target starts with required header
        stripped = text.strip()
        if not stripped.startswith(HEADER):
            sys.stderr.write(f"missing_required_header in {doc_name}\n")
            return 1

        # Find all digit sequences
        for m in re.finditer(r"\d+", text):
            digit_str = m.group(0)
            start_pos, end_pos = m.start(), m.end()

            # Find the enclosing line at this position
            line_start = text.rfind("\n", 0, start_pos)
            line_start = 0 if line_start == -1 else line_start + 1
            line_end = text.find("\n", end_pos)
            line_end = len(text) if line_end == -1 else line_end
            line_text = text[line_start:line_end]

            # Expand around digit_str to get token (including decimals, fractions, brackets)
            t_start = start_pos
            while t_start > line_start and text[t_start - 1] in "0123456789.-/[]()":
                t_start -= 1
            t_end = end_pos
            while t_end < line_end and text[t_end] in "0123456789.-/[]()":
                t_end += 1
            token = text[t_start:t_end].strip(".,()[]")

            # Check 1: Allowed formatted value or number from numbers.json
            if token in expanded_allowed or (not ("." in token or "/" in token) and digit_str in expanded_allowed):
                continue

            # Check 2: Does it match an allowlist context pattern on this line enclosing the digit?
            rel_start = start_pos - line_start
            rel_end = end_pos - line_start
            matched_allowlist = False
            for pat in allowlist_patterns:
                for pm in pat.finditer(line_text):
                    if pm.start() <= rel_start and rel_end <= pm.end():
                        matched_allowlist = True
                        break
                if matched_allowlist:
                    break

            if matched_allowlist:
                continue

            # Stray number found!
            snippet = text[max(0, start_pos - 20):min(len(text), end_pos + 20)].replace("\n", " ")
            stray_numbers.append({
                "doc": doc_name,
                "digit": digit_str,
                "token": token,
                "snippet": snippet
            })

    if stray_numbers:
        sys.stderr.write(f"check failed: {len(stray_numbers)} stray number(s) found:\n")
        for s in stray_numbers:
            sys.stderr.write(f"  [{s['doc']}] stray digit '{s['digit']}' in token '{s['token']}': ...{s['snippet']}...\n")
        return 1

    print("check passed: 0 stray numbers in rendered outputs")
    return 0


def main(argv=None) -> int:
    import argparse
    parser = argparse.ArgumentParser(description="Render and check S10c dev results")
    subparsers = parser.add_subparsers(dest="subcommand", required=True)

    extract_p = subparsers.add_parser("extract")
    extract_p.add_argument("--analysis", required=True)
    extract_p.add_argument("--expect-sha", required=True)
    extract_p.add_argument("--receipts-dir", required=True)
    extract_p.add_argument("--out", required=True)

    render_p = subparsers.add_parser("render")
    render_p.add_argument("--numbers", required=True)
    render_p.add_argument("--template", required=True)
    render_p.add_argument("--block-template", required=True)
    render_p.add_argument("--results-out", required=True)
    render_p.add_argument("--results-md", required=True)

    check_p = subparsers.add_parser("check")
    check_p.add_argument("--rendered", required=True)
    check_p.add_argument("--block-file", required=True)
    check_p.add_argument("--numbers", required=True)
    check_p.add_argument("--allowlist", required=True)

    args = parser.parse_args(argv)

    if args.subcommand == "extract":
        return extract_cmd(args.analysis, args.expect_sha, args.receipts_dir, args.out)
    elif args.subcommand == "render":
        return render_cmd(args.numbers, args.template, args.block_template, args.results_out, args.results_md)
    elif args.subcommand == "check":
        return check_cmd(args.rendered, args.block_file, args.numbers, args.allowlist)
    return 1


if __name__ == "__main__":
    sys.exit(main())
