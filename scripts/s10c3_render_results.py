def substitute(template_str: str, variables: Dict[str, str]) -> str:
    pattern = re.compile(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}")
    missing = set()

    def replace(match):
        key = match.group(1)
        if key not in variables:
            missing.add(key)
            return match.group(0)
        return variables[key]

    out = pattern.sub(replace, template_str)
    if missing:
        raise KeyError(f"Missing template variables: {sorted(missing)}")
    return out


